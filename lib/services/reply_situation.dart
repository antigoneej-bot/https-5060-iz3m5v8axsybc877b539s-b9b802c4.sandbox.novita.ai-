/// Conservative patterns for explicit, direct accounts. Ambiguous reports,
/// negations and hypotheticals fall back to the existing non-assuming response.
class ReplySituation {
  final String id;
  final List<String> listening;
  final String reflection, suggestion;
  const ReplySituation(
    this.id,
    this.listening,
    this.reflection,
    this.suggestion,
  );

  /// Do not turn another person's state or an earlier state into the writer's
  /// current feelings. These are deliberately conservative lexical guards.
  static bool uncertainPerspective(String text) => RegExp(
    r'예전에|옛날|지난해|작년|그때는|당시에는|지금은|이제는|더 이상|'
    r'(친구|동료|동생|언니|오빠|엄마|아빠|어머니|아버지|남편|아내|그 사람|그녀|그)(가|이|는|은)\s',
  ).hasMatch(text);

  static ReplySituation? detect(String text) {
    if (text.length > 500 ||
        RegExp(
          r'["“”「」『』]|아니|않|못|안\s|없|대신|라면|다면|했다면|했다고|했대|라고|더라고|소설에서|소설 속|대사|예를|가정|꿈|상상|농담|었으면|았으면|친구가|동료가|동생이|언니가|오빠가',
        ).hasMatch(text))
      return null;
    if (RegExp(r'예전에|옛날|지난해|작년|그때는|당시에는|지금은|이제는|더 이상').hasMatch(text))
      return null;
    bool has(String pattern) => RegExp(pattern).hasMatch(text);
    if (has(r'상사가 내 말을 무시') && has(r'화났|화가 났')) {
      return const ReplySituation(
        'dismissed_angry',
        [
          '상사가 네 말을 무시한 일에 화가 났다고 적어주었네. 네 말을 듣는 이 자리에서는 그 마음을 서둘러 덮지 않을게.',
          '네 말이 무시된 일과 그 뒤의 화를 함께 읽었어. 여기서는 네가 겪은 쪽의 이야기를 듣고 있어.',
          '내 말을 들어주지 않았던 일이 편지에 남아 있네. 화가 났다는 말도 그대로 받아둘게.',
        ],
        '상사가 한 행동과 네가 느낀 화를 구분해서 읽었어. 상대의 의도까지는 이 편지만으로 정하지 않을게.',
        '원한다면 그때 끝까지 전하고 싶었던 말을 한 문장만 적어봐. 바로 상대에게 보내지 않아도 돼.',
      );
    }
    if (has(r'^(오늘\s*)?(내가\s*|나는\s*)?상사에게 화(를\s*)?냈') && has(r'후회|마음에 걸|미안')) {
      return const ReplySituation(
        'anger_regret',
        [
          '상사에게 화를 낸 뒤에도 마음에 남는 것이 있구나. 그때의 일과 지금의 마음을 함께 듣고 있어.',
          '화를 냈다는 말 뒤에 남은 마음도 읽었어. 그 한 번의 행동만으로 너를 판단하지 않을게.',
          '편지는 화를 낸 순간에서 끝나지 않았네. 그 뒤에 남은 마음에도 자리를 내어줄게.',
        ],
        '화를 표현한 일과 그 뒤에 남은 마음은 서로 다른 부분이야. 어느 한쪽만으로 오늘을 설명하지 않을게.',
        '원한다면 화가 났던 이유와 다르게 표현하고 싶은 부분을 한 줄씩 나눠 적어봐.',
      );
    }
    if (has(r'상사가 칭찬|칭찬을? 받|칭찬받') && has(r'부담') && has(r'지만|는데|그런데')) {
      return const ReplySituation(
        'praise_pressure',
        [
          '칭찬 이야기와 부담스럽다는 말을 함께 적어주었네. 칭찬을 받았다고 꼭 기쁜 마음만 있어야 하는 건 아니야.',
          '칭찬 뒤에 부담이 남았다는 쪽도 듣고 있어. 겉으로 좋은 일처럼 보여도 네 마음을 한 가지로 정하지 않을게.',
          '칭찬받은 일과 부담스러운 마음이 같은 편지에 있네. 어느 쪽도 지우지 않고 읽을게.',
        ],
        '칭찬받은 사건과 부담을 느낀 마음이 함께 있어. 기뻤을 거라고 대신 결론 내리지 않을게.',
        '원한다면 칭찬 이후 무엇이 부담으로 느껴졌는지 한 가지만 적어봐.',
      );
    }
    if (has(r'^(오늘\s*)?(내가\s*|나는\s*)?면접.*떨어졌') &&
        has(r'(엄마|어머니)는 괜찮') &&
        has(r'괜찮') &&
        has(r'미안')) {
      return const ReplySituation(
        'interview_guilt',
        [
          '면접 결과에 관한 말 뒤에 엄마에게 미안한 마음도 남아 있네. 그 마음까지 함께 읽었어.',
          '면접 이야기만으로 끝나지 않는 편지였네. 엄마에게 미안하다는 말에도 조용히 귀를 기울일게.',
          '결과를 적은 문장과 미안한 마음을 적은 문장 사이에서 잠깐 멈췄어. 어느 한쪽만 골라 듣지 않을게.',
        ],
        '면접 결과와 엄마에게 느끼는 미안함은 구분해서 볼 수 있어. 엄마가 실제로 무엇을 기대하는지는 짐작하지 않을게.',
        '원한다면 지금 엄마에게 전하고 싶은 마음을 한 줄 적어봐. 보내지 않고 네 편지에만 남겨도 괜찮아.',
      );
    }
    if (uncertainPerspective(text)) return null;
    if (RegExp(r'^(오늘\s*)?나는\s').hasMatch(text) &&
        RegExp(r'(기쁘|기뻐|뿌듯|기쁜).*(지만|면서|동시에).*(불안|걱정|두렵)').hasMatch(text)) {
      return const ReplySituation(
        'joy_and_worry',
        [
          '기쁜 마음과 불안한 마음을 함께 적어주었네. 어느 한쪽을 골라야 하는 건 아니야.',
          '좋은 마음만 남기려고 애쓰지 않아도 돼. 네가 적어준 기쁨과 걱정을 같이 듣고 있어.',
          '기쁘면서도 걱정이 된다는 말이 마음에 남았어. 두 마음이 함께 있는 채로 이야기해도 좋아.',
          '뿌듯한 쪽도, 조심스러운 쪽도 이 편지에 머물 자리가 있어.',
        ],
        '기쁨과 걱정이 같은 일에서 생겼을 수도 있어. 둘 중 하나를 틀린 마음이라고 정하지 않을게.',
        '원한다면 기쁜 부분과 걱정되는 부분을 한 줄씩 나눠 적어봐. 지금 해결하지 않아도 돼.',
      );
    }
    for (final entry in _everyday) {
      final match = entry.pattern.firstMatch(text);
      if (match != null) {
        final tail = text.substring(match.end);
        if (tail.isEmpty || RegExp(r'^[.!?\s]*$').hasMatch(tail))
          return entry.situation;
      }
    }
    return null;
  }

