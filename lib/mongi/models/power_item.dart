/// "파워 부적" - 빛의 정수로 미리 사둘 수 있는 소모품.
///
/// 게임 안에서 우연히 만나는 "파워빛볼"([PowerOrb])과 완전히 동일한 효과
/// (10초 무적 모드 - [RunnerGame.activatePowerMode])를 유저가 원하는
/// 순간에 직접 발동할 수 있게 해준다. 감정 몬스터나 장애물(돌멩이/참새/
/// 개구리 등)에 계속 막혀 답답할 때 "지금 당장" 뚫고 지나가고 싶은 순간을
/// 위한 F2P 편의 상품이다.
///
/// [ReviveService]/[GachaService]와 동일한 설계 원칙: 확률/랜덤 요소 없이
/// "화폐를 내면 확정으로 인벤토리에 쌓인다" -> 게임 중 아무 때나 꺼내
/// 쓴다. 코어 루프를 유료화하는 것이 아니라(기존에도 파워빛볼은 무료로
/// 가끔 등장한다), 그 특별한 순간을 유저가 스스로 고를 수 있게 하는
/// 세 번째 옵션일 뿐이다.
class PowerCharmOffer {
  PowerCharmOffer._();

  /// 부적 1개를 구매하는 데 필요한 빛의 정수(소프트 화폐) 비용.
  /// 마음 상자 1회(30)보다 살짝 비싸게 잡아, "가끔 특별한 순간에" 쓰는
  /// 아이템이라는 느낌을 유지한다.
  static const int lightEssenceCost = 40;

  /// "여러 개 구매" 편의 버튼에서 한 번에 살 수 있는 개수(할인 없음 -
  /// 여러 번 사는 수고만 덜어줌, 마음 상자 묶음열기와 동일한 원칙).
  static const int bulkQuantity = 5;
}
