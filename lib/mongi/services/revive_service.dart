/// "생명의 물" - 목숨을 다 썼을 때 광고 없이 화폐로 즉시 부활하는 F2P
/// 편의 상품의 가격 정의.
///
/// [GachaService]와 동일한 설계: 확률/랜덤 요소 없이 "화폐를 내면 확정으로
/// 즉시 목숨이 가득 채워진다"는 단순한 소모품이다. 무료 이어하기([RunnerGame.
/// freeRevivesPerRun]번)와 광고 보고 이어하기 사이에 세 번째 선택지로 끼워
/// 넣어, "지금 광고 보기 귀찮은데 화폐는 좀 있다"는 순간에 자연스러운
/// 소비처가 되도록 한다.
///
/// 코어 루프 자체를 유료화하지 않는다는 원칙(순수 코스메틱만 유료화)과는
/// 별개다 - 이건 "실패해도 계속할 수 있는 기존 무료/광고 경로"에 화폐로
/// 시간을 아끼는 세 번째 옵션을 하나 더한 것뿐이라, 강제성이 없다.
class ReviveService {
  ReviveService._();

  /// 광고 없이 즉시 부활하는 데 필요한 빛의 정수(소프트 화폐) 비용.
  /// 마음 상자 1회(30) 대비 살짝 비싼 수준으로 잡아, "가볍게 쓸 수는
  /// 있지만 매번 남발하긴 아까운" 가격대를 유지한다.
  static const int lightEssenceCost = 50;
}
